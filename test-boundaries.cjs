const assert=require('node:assert/strict');
const {boundaryAliasIndex,matchBoundary,zoneState,oblastState}=require('./boundaries.js');
const parents={'Броварський район':'Київська','Бериславський район':'Херсонська','Самарівський район':'Дніпропетровська',"Кам’янський район":'Дніпропетровська'};
const regions=new Set(['Київська','Херсонська','Дніпропетровська','м. Київ']);
const districts=new Set(Object.keys(parents));
const idx=boundaryAliasIndex(regions,parents,{'Новомосковський район':'Самарівський район'});
const f=properties=>({properties});
assert.equal(matchBoundary(f({name:'Київська область'}),idx,regions),'Київська');
assert.equal(matchBoundary(f({name:'Київ'}),idx,regions),'м. Київ');
assert.equal(matchBoundary(f({name:'Броварський район',region:'Київська область'}),idx,districts),'Броварський район');
assert.equal(matchBoundary(f({NAME_UA:'Новомосковський район'}),idx,districts),'Самарівський район');
assert.equal(matchBoundary(f({name:"Кам'янський район"}),idx,districts),'Кам’янський район');
assert.equal(matchBoundary(f({name:'Невідомий район'}),idx,districts),null);
const a={status:'active',threat_type:'drone'},p={...a,scope:'district'},e={status:'ended'};
assert.equal(oblastState(p,false).status,'unknown');
assert.equal(oblastState(a,false).status,'active');
assert.equal(zoneState(p,a,false).status,'active');
assert.equal(zoneState(p,null,false).status,'unknown');
assert.equal(zoneState(a,e,false).status,'active');
assert.equal(zoneState(p,e,false).status,'ended');
assert.equal(zoneState(a,a,true).status,'unknown');
assert.equal(oblastState(a,true).status,'unknown');
console.log('14 assertions passed');
